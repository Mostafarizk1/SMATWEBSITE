// Builds content/gulf-map.ts from the country outlines in the client's HTML concept (smat-v3.html).
// Run once: node scripts/extract-map.mjs "<path to smat-v3.html>"
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(process.argv[2], "utf8");
const svg = html.slice(html.indexOf('id="mapSvg"'), html.indexOf("</svg>", html.indexOf('id="mapSvg"')));
const grab = (groupId) => {
  const g = svg.slice(svg.indexOf(`<g id="${groupId}">`), svg.indexOf("</g>", svg.indexOf(`<g id="${groupId}">`)));
  return [...g.matchAll(/<path class="[^"]*"(?: id="c-([A-Z]{3})")? d="([^"]+)"/g)].map((m) => ({ id: m[1] ?? null, d: m[2] }));
};
const bbox = (d) => {
  const n = d.match(/-?\d+(?:\.\d+)?/g).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1);
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
};

// The crop: from Türkiye and Egypt in the west to Oman in the east.
const view = { x: 20, y: 50, w: 1280, h: 630 };
const inView = (b) => b.x1 > view.x && b.x0 < view.x + view.w && b.y1 > view.y && b.y0 < view.y + view.h;

const ctx = grab("mCtx");
const act = grab("mAct");

// Qatar is drawn as a context country in the concept; find it by where Doha falls (x≈963, y≈458).
const isQatar = (p) => { const b = bbox(p.d); return b.x0 < 963 && b.x1 > 940 && b.y0 < 458 && b.y1 > 458 && b.x1 - b.x0 < 60; };
const qatar = ctx.find(isQatar);
if (!qatar) throw new Error("Qatar outline not found");

const ours = { SAU: "sa", ARE: "ae", OMN: "om", KWT: "kw", EGY: "eg", TUR: "tr" };
const active = act.filter((p) => ours[p.id]).map((p) => ({ id: ours[p.id], d: p.d }));
active.push({ id: "qa", d: qatar.d });

const context = [...ctx.filter((p) => p !== qatar), ...act.filter((p) => !ours[p.id])].filter((p) => inView(bbox(p.d))).map((p) => p.d);

const out = `// GENERATED by scripts/extract-map.mjs from the client's map concept. Do not edit by hand.
// Country outlines for the region, in the concept's own projection (x = 795.2 + (lon − 46.7) × 34.8,
// y = 471.7 − (lat − 24.7) × 22.53). Bahrain is too small to have an outline at this scale: pin only.
import type { Market } from "./markets";

export const gulfMapView = { x: ${view.x}, y: ${view.y}, w: ${view.w}, h: ${view.h} } as const;

/** Markets we serve: highlighted. */
export const gulfMapActive: { id: Market["id"]; d: string }[] = ${JSON.stringify(active, null, 2)};

/** Neighbouring countries: drawn dim, for geography only. */
export const gulfMapContext: string[] = ${JSON.stringify(context, null, 2)};
`;
writeFileSync("content/gulf-map.ts", out);
console.log("active", active.map((a) => a.id).join(","), "| context paths", context.length, "| bytes", out.length);
